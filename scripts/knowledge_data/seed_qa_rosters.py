def main():
    s = make_session()
    listed = s.get(f"{BASE}/api/knowledge/list", params={"include_archived": "true"}, timeout=30)
    listed.raise_for_status()
    items = listed.json()
    by_title = {i["title"]: i["id"] for i in items}

    # 幂等：新标题已存在则不重复建
    for old_title, e in ENTRIES:
        if e["title"] in by_title:
            log(f"跳过（已存在）「{e['title']}」")
            continue
        # 删旧条目（问答版替换叙述版）
        if old_title and old_title in by_title:
            r = s.delete(f"{BASE}/api/knowledge/{by_title[old_title]}", timeout=60)
            log(f"DELETE [{r.status_code}] 「{old_title}」")
            time.sleep(1)
        r = s.post(f"{BASE}/api/knowledge/create", json={
            "title": e["title"], "category": e["category"], "tags": e["tags"],
            "summary": e["summary"][:200], "content": e["content"],
        }, timeout=120)
        log(f"{'OK ' if r.status_code == 200 else 'FAIL'} 「{e['title']}」HTTP {r.status_code}")
        if r.status_code != 200:
            print(r.text[:300])
            sys.exit(1)
        time.sleep(1.5)
    log("完成。注意：DELETE 产生孤儿 chunk，须重启服务清索引。")


if __name__ == "__main__":
    main()
